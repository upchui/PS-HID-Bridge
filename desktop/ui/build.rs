use cxx_qt_build::{CxxQtBuilder, QResource, QResources, QmlFile, QmlModule};

fn main() {
    // Link with lld: cxx-qt would otherwise get GNU gold, which emits two
    // .init_array sections -- the loader runs only one, so the static
    // initializers that register the QML module's resources never run.
    // (Only this binary: the CLI and the tests keep the default linker, so
    // all of them can share one target directory.)
    println!("cargo:rustc-link-arg-bins=-fuse-ld=lld");

    let module = QmlModule::new("PSHIDBridge")
        // Colours and sizes for everything else.
        .qml_file(QmlFile::from("qml/Style.qml").singleton(true))
        // Icon path data, generated by tools/gen_icons.py from icons/*.svg.
        .qml_file(QmlFile::from("qml/Icons.qml").singleton(true))
        .qml_files([
            "qml/Main.qml",
            // pages
            "qml/StatusPage.qml",
            "qml/InputPage.qml",
            "qml/TriggersPage.qml",
            "qml/BoardPage.qml",
            "qml/FirmwarePage.qml",
            "qml/WizardPage.qml",
            // building blocks
            "qml/AppPage.qml",
            "qml/Card.qml",
            "qml/Banner.qml",
            "qml/StatTile.qml",
            "qml/Pill.qml",
            "qml/HelpHint.qml",
            "qml/Segmented.qml",
            "qml/NavItem.qml",
            "qml/AppButton.qml",
            "qml/AppSwitch.qml",
            "qml/AppIcon.qml",
            "qml/DeviceList.qml",
            "qml/TriggerEditor.qml",
            "qml/CurvePlot.qml",
            "qml/KeyboardTypeChooser.qml",
            "qml/UsbInstall.qml",
        ]);

    // The app icon (also in the AppImage's .desktop entry), for the windows:
    // qrc:/ps-hid-bridge/app-icon.svg, see src/window_icon.h.
    // (QResourceFile, needed for the alias, is not re-exported: take it from a QResource.)
    let icon_file = QResource::new()
        .file("../packaging/icons/io.github.thealhu.pshidbridge.svg")
        .get_files()
        .next()
        .unwrap()
        .clone()
        .alias("app-icon.svg");
    let app_icon = QResources::new().resource(QResource::new().prefix("/ps-hid-bridge").file(icon_file));
    println!("cargo:rerun-if-changed=src/window_icon.h");

    CxxQtBuilder::new_qml_module(module)
        .qrc_resources(app_icon)
        .include_dir(concat!(env!("CARGO_MANIFEST_DIR"), "/src"))
        .files(["src/controller.rs", "src/window_icon.rs"])
        .qt_module("Quick")
        .qt_module("QuickControls2")
        .build();
}
