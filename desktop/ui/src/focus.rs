//! Window rule on KDE Plasma: a small KWin script reports every window
//! activation over D-Bus (same approach as kdotool). Wayland offers no other
//! way for an application to learn which window has the focus.

use std::sync::Mutex;
use std::time::Duration;

use zbus::blocking::{Connection, Proxy, connection};

const OBJECT_PATH: &str = "/FocusWatcher";
const INTERFACE: &str = "io.github.thealhu.ps5hidbridge.Focus";
const SCRIPT_NAME: &str = "ps5-hid-bridge-focus";

struct FocusIface {
    pattern: String,
    last: Mutex<Option<bool>>,
    on_change: Box<dyn Fn(bool) + Send + Sync>,
}

#[zbus::interface(name = "io.github.thealhu.ps5hidbridge.Focus")]
impl FocusIface {
    fn activated(&self, caption: String, resource_class: String, desktop_file: String) {
        let hit = [caption, resource_class, desktop_file]
            .iter()
            .any(|s| !s.is_empty() && s.to_lowercase().contains(&self.pattern));
        let mut last = self.last.lock().unwrap();
        if *last != Some(hit) {
            *last = Some(hit);
            (self.on_change)(hit);
        }
    }
}

pub struct FocusWatcher {
    conn: Connection,
}

fn script(service: &str) -> String {
    format!(
        r#"// Generated by PS5 HID Bridge: reports the active window.
function report(w) {{
    if (!w) {{
        callDBus("{service}", "{OBJECT_PATH}", "{INTERFACE}", "Activated", "", "", "");
        return;
    }}
    callDBus("{service}", "{OBJECT_PATH}", "{INTERFACE}", "Activated",
             String(w.caption || ""), String(w.resourceClass || ""), String(w.desktopFileName || ""));
}}
if (workspace.windowActivated) {{
    workspace.windowActivated.connect(report);
    report(workspace.activeWindow);
}} else {{
    workspace.clientActivated.connect(report);
    report(workspace.activeClient);
}}
"#
    )
}

fn scripting(conn: &Connection) -> zbus::Result<Proxy<'_>> {
    Proxy::new(conn, "org.kde.KWin", "/Scripting", "org.kde.kwin.Scripting")
}

/// Is KWin reachable on the session bus?
pub fn kwin_available() -> bool {
    let Ok(conn) = Connection::session() else {
        return false;
    };
    let Ok(dbus) = zbus::blocking::fdo::DBusProxy::new(&conn) else {
        return false;
    };
    zbus::names::BusName::try_from("org.kde.KWin")
        .ok()
        .and_then(|n| dbus.name_has_owner(n).ok())
        .unwrap_or(false)
}

impl FocusWatcher {
    /// Watch for windows whose caption, class or desktop file contains
    /// `pattern` (case-insensitive); `on_change(true/false)` on every change.
    pub fn start(pattern: &str, on_change: impl Fn(bool) + Send + Sync + 'static) -> Result<Self, String> {
        let iface = FocusIface {
            pattern: pattern.to_lowercase(),
            last: Mutex::new(None),
            on_change: Box::new(on_change),
        };
        let conn = connection::Builder::session()
            .and_then(|b| b.serve_at(OBJECT_PATH, iface))
            .and_then(|b| b.build())
            .map_err(|e| format!("D-Bus: {e}"))?;
        let service = conn
            .unique_name()
            .map(|n| n.to_string())
            .ok_or("no D-Bus address")?;

        let dir = std::env::var_os("XDG_RUNTIME_DIR")
            .map(std::path::PathBuf::from)
            .unwrap_or_else(std::env::temp_dir);
        let path = dir.join(format!("{SCRIPT_NAME}.js"));
        std::fs::write(&path, script(&service)).map_err(|e| format!("{}: {e}", path.display()))?;

        {
            let proxy = scripting(&conn).map_err(|e| format!("KWin: {e}"))?;
            let _: zbus::Result<bool> = proxy.call("unloadScript", &(SCRIPT_NAME,));
            let id: i32 = proxy
                .call("loadScript", &(path.display().to_string(), SCRIPT_NAME))
                .map_err(|e| format!("KWin-Skript laden: {e}"))?;
            if id < 0 {
                return Err("KWin hat das Skript abgelehnt.".into());
            }
            Proxy::new(
                &conn,
                "org.kde.KWin",
                format!("/Scripting/Script{id}"),
                "org.kde.kwin.Script",
            )
            .and_then(|p| p.call::<_, _, ()>("run", &()))
            .map_err(|e| format!("KWin-Skript starten: {e}"))?;
        }
        // Give KWin a moment to report the current window.
        std::thread::sleep(Duration::from_millis(50));
        Ok(Self { conn })
    }
}

impl Drop for FocusWatcher {
    fn drop(&mut self) {
        if let Ok(p) = scripting(&self.conn) {
            let _: zbus::Result<bool> = p.call("unloadScript", &(SCRIPT_NAME,));
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn script_mentions_service_and_both_signal_names() {
        let s = script(":1.42");
        assert!(s.contains("\":1.42\""));
        assert!(s.contains("windowActivated") && s.contains("clientActivated"));
    }
}
