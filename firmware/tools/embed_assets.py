#!/usr/bin/env python3
"""Embed the web interface files as gzip-compressed C arrays.

Usage: embed_assets.py OUTPUT_DIR FILE...
Writes OUTPUT_DIR/web_assets.h and OUTPUT_DIR/web_assets.c. The output is
deterministic (gzip mtime 0) so rebuilds are reproducible.
"""

from __future__ import annotations

import gzip
import os
import sys

TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".svg": "image/svg+xml",
    ".ico": "image/x-icon",
}

HEADER = """// Generated by firmware/tools/embed_assets.py -- do not edit.
#ifndef PSHB_WEB_ASSETS_H
#define PSHB_WEB_ASSETS_H

#include <stddef.h>
#include <stdint.h>

typedef struct {
    const char *path;
    const char *type;
    const uint8_t *data;  // gzip
    uint32_t len;
} web_asset_t;

extern const web_asset_t web_assets[];
extern const size_t web_assets_count;

#endif
"""


def main() -> int:
    out_dir, files = sys.argv[1], sys.argv[2:]
    os.makedirs(out_dir, exist_ok=True)
    parts = ["// Generated by firmware/tools/embed_assets.py -- do not edit.\n",
             '#include "web_assets.h"\n\n']
    table = []
    total = 0
    for i, path in enumerate(sorted(files)):
        name = os.path.basename(path)
        ext = os.path.splitext(name)[1]
        if ext not in TYPES:
            raise SystemExit(f"unknown file type: {name}")
        with open(path, "rb") as f:
            raw = f.read()
        data = gzip.compress(raw, compresslevel=9, mtime=0)
        total += len(data)
        body = ",".join(str(b) for b in data)
        parts.append(f"static const uint8_t asset_{i}[{len(data)}] = {{{body}}};\n")
        table.append(f'    {{"/{name}", "{TYPES[ext]}", asset_{i}, {len(data)}}},\n')
    parts.append("\nconst web_asset_t web_assets[] = {\n" + "".join(table) + "};\n")
    parts.append(f"const size_t web_assets_count = {len(table)};\n")
    with open(os.path.join(out_dir, "web_assets.h"), "w") as f:
        f.write(HEADER)
    with open(os.path.join(out_dir, "web_assets.c"), "w") as f:
        f.write("".join(parts))
    print(f"embedded {len(table)} web files, {total} bytes gzip")
    return 0


if __name__ == "__main__":
    sys.exit(main())
