#!/usr/bin/env python3
"""Generate the icon data of the desktop app and the board's web interface
from the line icons in desktop/ui/icons/*.svg (24x24, stroke 2, drawn for
this project; the SVG files are the only source).

- desktop/ui/qml/Icons.qml: SVG path data per icon (stroked and filled
  parts), drawn by AppIcon.qml with QtQuick.Shapes in any colour.
- firmware/src/web/index.html: the <symbol> sprite between the markers
  <!-- icons:begin --> and <!-- icons:end -->, used with <svg><use href="#i-name">.

Usage: tools/gen_icons.py [--check]
"""

import argparse
import os
import re
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
ICONS = os.path.join(ROOT, "desktop", "ui", "icons")
QML_OUT = os.path.join(ROOT, "desktop", "ui", "qml", "Icons.qml")
WEB_HTML = os.path.join(ROOT, "firmware", "src", "web", "index.html")
# Icons the web interface uses (keep its size small).
WEB_ICONS = ["status", "network", "key", "board", "update", "gamepad", "check", "warning", "error",
             "external", "power", "latency", "download"]
NS = "{http://www.w3.org/2000/svg}"


def num(v):
    return float(v) if v is not None else 0.0


def fmt(x):
    s = f"{x:.3f}".rstrip("0").rstrip(".")
    return s if s not in ("-0", "") else "0"


def to_path(el):
    """SVG element -> path data."""
    tag = el.tag.replace(NS, "")
    if tag == "path":
        return el.get("d")
    if tag == "circle":
        cx, cy, r = num(el.get("cx")), num(el.get("cy")), num(el.get("r"))
        return (f"M{fmt(cx - r)} {fmt(cy)}a{fmt(r)} {fmt(r)} 0 1 0 {fmt(2 * r)} 0"
                f"a{fmt(r)} {fmt(r)} 0 1 0 {fmt(-2 * r)} 0Z")
    if tag == "rect":
        x, y, w, h = (num(el.get(k)) for k in ("x", "y", "width", "height"))
        rx = min(num(el.get("rx")), w / 2, h / 2)
        if rx == 0:
            return f"M{fmt(x)} {fmt(y)}h{fmt(w)}v{fmt(h)}h{fmt(-w)}Z"
        a = f"a{fmt(rx)} {fmt(rx)} 0 0 1"
        return (f"M{fmt(x + rx)} {fmt(y)}h{fmt(w - 2 * rx)}{a} {fmt(rx)} {fmt(rx)}v{fmt(h - 2 * rx)}"
                f"{a} {fmt(-rx)} {fmt(rx)}h{fmt(-(w - 2 * rx))}{a} {fmt(-rx)} {fmt(-rx)}"
                f"v{fmt(-(h - 2 * rx))}{a} {fmt(rx)} {fmt(-rx)}Z")
    raise SystemExit(f"unsupported SVG element <{tag}>")


def load():
    icons = {}
    for name in sorted(os.listdir(ICONS)):
        if not name.endswith(".svg"):
            continue
        root = ET.parse(os.path.join(ICONS, name)).getroot()
        stroke, fill, inner = [], [], []
        for el in root:
            d = to_path(el)
            if el.get("fill") not in (None, "none"):
                fill.append(d)
            else:
                stroke.append(d)
            inner.append(ET.tostring(el, encoding="unicode").replace(f' xmlns:ns0="{NS[1:-1]}"', "")
                         .replace("ns0:", ""))
        icons[name[:-4]] = {"s": "".join(stroke), "f": "".join(fill), "svg": "".join(inner)}
    return icons


def qml(icons):
    lines = ["pragma Singleton",
             "import QtQuick",
             "",
             "// Generated by tools/gen_icons.py from desktop/ui/icons/*.svg -- do not edit.",
             "QtObject {",
             "    readonly property var paths: ({"]
    for name, d in icons.items():
        lines.append(f'        "{name}": {{ s: "{d["s"]}", f: "{d["f"]}" }},')
    lines += ["    })", "}", ""]
    return "\n".join(lines)


def web_sprite(icons):
    syms = []
    for name in WEB_ICONS:
        body = re.sub(r'fill="#000"', 'fill="currentColor"', icons[name]["svg"])
        syms.append(f'<symbol id="i-{name}" viewBox="0 0 24 24">{body}</symbol>')
    return ('<svg xmlns="http://www.w3.org/2000/svg" hidden>'
            "<defs>" + "".join(syms) + "</defs></svg>")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="only check that the outputs are up to date")
    args = ap.parse_args()
    icons = load()
    outputs = {QML_OUT: qml(icons)}
    html = open(WEB_HTML).read()
    begin, end = "<!-- icons:begin -->", "<!-- icons:end -->"
    if begin in html:
        a = html.index(begin) + len(begin)
        b = html.index(end)
        outputs[WEB_HTML] = html[:a] + "\n" + web_sprite(icons) + "\n" + html[b:]
    stale = [p for p, text in outputs.items() if not os.path.exists(p) or open(p).read() != text]
    if args.check:
        for p in stale:
            print(f"{os.path.relpath(p, ROOT)} is out of date (run tools/gen_icons.py)", file=sys.stderr)
        return 1 if stale else 0
    for p in stale:
        with open(p, "w") as f:
            f.write(outputs[p])
        print(f"wrote {os.path.relpath(p, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
